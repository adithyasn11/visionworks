"""
Write docs/SAFETY_EVALUATION.md from the three results files, so the document can never drift from the numbers:

    ppe_training/reports/SEGMENT_EVAL.json        ppe_training/eval_segments.py      (§14.A, §14.G)
    backend/eval/results/safety_evaluation.json   backend/eval/safety_scenarios.py   (§14.B, part of §14.C)
    backend/eval/results/real_footage.json        backend/eval/real_footage.py       (§14.C, §14.D, §14.E)

Run:  venv/Scripts/python.exe backend/eval/write_report.py
"""

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "docs", "SAFETY_EVALUATION.md")


def load(*parts):
    path = os.path.join(ROOT, *parts)
    return json.load(open(path, encoding="utf-8")) if os.path.isfile(path) else None


def pc(v, d=1):
    return "n/a" if v is None else f"{v * 100:.{d}f}%"


def err(k, of, rate, upper):
    if not of:
        return "n/a"
    return f"0 of {of} (at most {pc(upper)})" if k == 0 else f"{k} of {of} ({pc(rate)}; at most {pc(upper)})"


def ppe_table(results):
    rows = ["| System | Segments | False accusations (of those wearing it) | False compliance (of those without it) | Abstained | Coverage | Error among verdicts |",
            "|---|---:|---:|---:|---:|---:|---:|"]
    names = {"B0 per-frame": "B0 per-frame (one frame decides)", "B1 majority vote": "B1 majority vote over the window", "ours": "**Ours** (clear frames, 60 % / 90 %, abstains)"}
    for k in ("B0 per-frame", "B1 majority vote", "ours"):
        r = results[k]
        rows.append(f"| {names[k]} | {r['n']} | {err(r['false_accusation'], r['worn'], r['false_accusation_rate'], r['false_accusation_upper95'])} | "
                    f"{err(r['false_compliance'], r['missing'], r['false_compliance_rate'], r['false_compliance_upper95'])} | {r['abstained']} | {pc(r['coverage'])} | {pc(r['error_rate'])} |")
    return rows


def main():
    seg = load("ppe_training", "reports", "SEGMENT_EVAL.json")
    scen = load("backend", "eval", "results", "safety_evaluation.json")
    real = load("backend", "eval", "results", "real_footage.json")
    md = ["# VisionWorks safety evaluation", "",
          "Generated by `backend/eval/write_report.py` from the results files; every number below is read from them. "
          "Re-run the three evaluation scripts and this one to bring it up to date (design §14, Step 17).", "",
          "**How to read it.** A *false accusation* is flagging someone who was wearing the item: the error that matters most. "
          "*Abstaining* (\"could not verify\") is not an error: it is the system refusing to guess, and it is counted, not hidden. "
          "A count of zero is given with its 95 % upper bound by the rule of three (3 / N); other counts with the upper end of the 95 % Wilson interval. "
          "*Coverage* is the share of cases where the system gave a verdict.", ""]

    # ── A and G ──
    md += ["## 1. Helmet and vest: our evidence layer against two simpler systems (§14.A, §14.G)", ""]
    if not seg:
        md += ["Not run yet (`ppe_training/eval_segments.py`).", ""]
    else:
        main_set, all_set = seg["sets"]["valB"], seg["sets"]["val"]
        d = seg["defaults"]
        md += [f"**Data.** Construction-PPE (Ultralytics, CC BY 4.0, partly generated imagery), whose labels say explicitly when a helmet or vest is missing. "
               f"Main result: the {main_set['images']} validation images never used in training or in choosing the model (valB), {main_set['segments']} person-and-item segments. "
               f"Each segment is up to {seg['frames_per_segment']} frames: the image itself, then the same still scene through slightly different camera moments (shift, zoom, light, blur, JPEG), "
               f"every frame read by the production detector (`{seg.get('weights')}`), association and clear-frame gate. **People do not move or turn here**, so this measures the decision against a real "
               f"detector's frame-to-frame jitter on a camera, not against motion, turning or occlusion; own footage (§14.A as planned: 480 recorded segments) has not been recorded.", "",
               f"**Systems.** B0 decides from one frame (the clean image): no detection of {d['seen_threshold']} or more on the person means a violation. B1 takes a majority over "
               f"{d['window']} frames, with no clear-frame gate and no abstention. Ours is the product as shipped: presence {d['presence']}, absence {d['absence']}, window {d['window']}, "
               f"at least {d['min_clear_frames']} clear frames, otherwise UNVERIFIABLE.", "",
               "### Both items (main result)", ""] + ppe_table(main_set["results"]["both items"]) + [""]
        for item in ("helmet", "vest"):
            md += [f"### {item.capitalize()}", ""] + ppe_table(main_set["results"][item]) + [""]
        b0, b1, ours = (main_set["results"]["both items"][k] for k in ("B0 per-frame", "B1 majority vote", "ours"))
        md += ["### What it shows", "",
               f"- Ours wrongly flags **{ours['false_accusation']} of {ours['worn']}** people who were wearing the item ({pc(ours['false_accusation_rate'])}), against "
               f"{b0['false_accusation']} ({pc(b0['false_accusation_rate'])}) for the per-frame system and {b1['false_accusation']} ({pc(b1['false_accusation_rate'])}) for the majority vote: "
               f"about {round(b0['false_accusation'] / max(1, ours['false_accusation']))} times fewer than per-frame.",
               f"- The price is abstention: ours gives a verdict on {pc(ours['coverage'])} of segments and says it could not verify the rest ({ours['abstained']}). "
               f"Among the verdicts it gives, {pc(ours['error_rate'])} are wrong, against {pc(b0['error_rate'])} and {pc(b1['error_rate'])}.",
               "- The majority vote is WORSE than one frame here: with no clear-frame gate it accuses small, distant people whose items the detector cannot see in any frame. "
               "That is the case the clear-frame gate exists for.",
               "- **The target of zero false accusations is not met.** Every one of our false accusations is a case where the detector found the item in none of the frames: "
               "a helmet behind an excavator's cab glass, a small red helmet on a partly hidden worker, a grey (non hi-vis) vest the model does not recognise, a close-up with the helmet "
               "covered by a device, and two workers in grey uniforms that the dataset labels as wearing a vest although no vest is visible (arguably label errors). "
               "A temporal rule cannot fix an error that is the same in every frame; these become POTENTIAL_VIOLATION flags, which a person reviews before anything happens.", ""]
        md += ["### By person height (both items): false accusations", "",
               "| Person height | Segments | B0 per-frame | B1 majority vote | Ours | Ours abstained |", "|---|---:|---:|---:|---:|---:|"]
        for label, r in main_set["by_size"].items():
            md.append(f"| {label} | {r['ours']['n']} | " + " | ".join(err(r[k]["false_accusation"], r[k]["worn"], r[k]["false_accusation_rate"], r[k]["false_accusation_upper95"])
                                                                       for k in ("B0 per-frame", "B1 majority vote", "ours")) + f" | {r['ours']['abstained']} |")
        md += ["", "Below 90 px tall nobody can be judged reliably: the per-frame and majority systems accuse about half of those wearing the item; ours abstains on almost all of them.", "",
               "### Threshold sweep: why 0.60 and 0.90", "", "![Error against coverage](../ppe_training/reports/segment_sweep.png)", "",
               f"{len(main_set['sweep'])} settings (presence 0.4 to 0.7, absence 0.7 to 0.95, window 10 to 45 frames) all lie between about "
               f"{pc(min(s['error_rate'] for s in main_set['sweep']))} and {pc(max(s['error_rate'] for s in main_set['sweep']))} error at "
               f"{pc(min(s['coverage'] for s in main_set['sweep']))} to {pc(max(s['coverage'] for s in main_set['sweep']))} coverage; the two baselines sit at 100 % coverage and over 10 % error. "
               "The shipped setting (0.6 / 0.9 / 30) is in the middle of that band: stricter settings (presence 0.7, absence 0.95) cut the error a little further at a few points less coverage. "
               "The choice is a trade-off on this curve, not a tuned optimum; the full table is in `ppe_training/reports/SEGMENT_EVAL.md`.", "",
               f"**A larger, slightly less clean set.** On all {all_set['images']} validation images ({all_set['segments']} segments; half of them were used to pick the training epoch): ours "
               f"{all_set['results']['both items']['ours']['false_accusation']} false accusations of {all_set['results']['both items']['ours']['worn']}, per-frame "
               f"{all_set['results']['both items']['B0 per-frame']['false_accusation']}, majority {all_set['results']['both items']['B1 majority vote']['false_accusation']}.", ""]

    # ── B ──
    md += ["## 2. Scenarios through the real engine (§14.B)", ""]
    if not scen:
        md += ["Not run yet (`backend/eval/safety_scenarios.py`).", ""]
    else:
        t = scen["totals"]
        md += [f"Each scenario ran {scen['variants_per_scenario']} times, at 10, 15 and 25 frames a second, with its timing and positions varied, through `SafetySession`: the zone tracker, "
               "the rule engine, the PPE evidence layer, man-down, the head count and the writer into a real SQLite file; every outcome is read back from that file. "
               "What the models see is scripted (boxes, zones, items, poses), so this measures the logic, not the models' eyes. S1n to S3n replace the perfect detector with "
               "the PPE model's measured per-frame error rates on clear frames (independent from frame to frame; correlated errors are what section 1 measures).", "",
               f"**{t['correct']} correct, {t['abstained']} abstained, {t['wrong']} wrong of {t['runs']} runs.**", "",
               "| Scenario | Expected | Runs | Correct | Abstained | Wrong | Timing, worst run |", "|---|---|---:|---:|---:|---:|---|"]
        for s in scen["scenarios"]:
            parts = []
            for key, label in (("entry_error_s", "entry"), ("exit_error_s", "exit"), ("dwell_error_s", "stay")):
                if s["timing"].get(key):
                    parts.append(f"{label} ±{s['timing'][key]['max_abs']:.2f} s")
            if s.get("time_to_alert_s"):
                parts.append(f"alert {s['time_to_alert_s']['median']} s after the fall (median; {s['time_to_alert_s']['max']} s worst)")
            md.append(f"| {s['id']} {s['title']} | {s['expected']} | {s['runs']} | {s['correct']} | {s['abstained']} | {s['wrong']} | {', '.join(parts)} |")
        md += ["", "Variants inside each scenario (from the per-run results): S4 far away and head cut off; S5 overlapping (both UNVERIFIABLE) and side by side (judged separately); "
               "S7 over and within the limit; S8 wrong route, lost from view and the right exit; S9 alone and two people; S10 2, 3.5 and 6 s out of view (6 s is past the 5 s "
               "\"lost\" point, and the visit still continues); M2 bending over, sitting upright and crawling. The per-run outcomes and the confusion counts are in "
               "`backend/eval/results/safety_evaluation.json`.", ""]

    # ── C, D, E ──
    md += ["## 3. The whole chain on real video (§14.C, §14.D, §14.E)", ""]
    if not real:
        md += ["Not run yet (`backend/eval/real_footage.py`).", ""]
    else:
        hw = real["hardware"]
        md += [f"Hardware: **{hw['gpu']}**, {hw['cpu']}, {hw['cores']} CPU threads{', ' + str(hw['ram_gb']) + ' GB RAM' if hw.get('ram_gb') else ''}, {hw['os']}, torch {hw['torch']}. "
               f"Pose model on the original frame up to {real['config']['pose_max_width']} px wide; PPE model every {real['config']['ppe_every_n_frames']} frames up to "
               f"{real['config']['ppe_max_width']} px, with close-up crops below {real['config']['ppe_crop_below_px']:g} px; the safety layer with man-down, head-count and helmet-and-vest rules "
               "on a whole-picture zone; up to the first two minutes of each clip.", "",
               "| Clip | Seconds | Input | Processed fps | ms per frame (95th pct) | Pose / PPE / safety ms | Man-down flags |", "|---|---:|---:|---:|---:|---:|---:|"]
        for c in real["clips"]:
            s = c["speed"]
            md.append(f"| {c['clip']} | {c['video_seconds']} | {c['source_resolution']} | {s['processed_fps']} | {s['ms_per_frame_mean']} ({s['ms_per_frame_p95']}) | "
                      f"{s['pose_ms_mean']} / {s['ppe_ms_mean']} / {s['safety_layer_ms_mean']} | {c['man_down']['flags']} |")
        mo = real["man_down_overall"]
        md += ["", f"- **Speed (§14.E).** Target 10 processed frames a second with pose and PPE: "
               + ("met on every clip." if all(c["speed"]["processed_fps"] >= 10 for c in real["clips"]) else "NOT met on every clip (see the table)."),
               "- **Alert latency.** A decision is made inside the frame that triggers it, so the event-to-decision time is one frame's processing time (the table's ms per frame). "
               "The live view shows it in that frame's message. The Review queue sees it after the background sync to Postgres and the dashboard's 15 s poll, so add up to about a minute; "
               "that part depends on the network and was not measured here.",
               f"- **Man-down false alarms (§14.C).** None of these clips shows anyone falling, so every man-down flag is a false alarm: **{mo['false_alarms']} in {mo['video_minutes']} minutes** "
               f"({mo['false_alarms_per_hour']} an hour; target at most 1). That is too little normal footage to state an hourly rate with confidence (the plan asks for an hour with hard negatives).",
               "- **Man-down recall and time to alert** on real falls: not measured, no fall has been recorded. On scripted falls (scenario M1) the alert comes "
               + (f"{next(s for s in scen['scenarios'] if s['id'] == 'M1')['time_to_alert_s']['median']} s after the fall (median), within the 8 s target." if scen else "(not run)."),
               "- **Head count (§14.D).** The counts per second are in `backend/eval/results/real_footage.json`. Checked by eye against sampled frames during Step 15: they match where people "
               "are large enough, and undercount tiny, distant people, which the 60 px floor turns into \"could not verify\" rather than a false lone-worker flag.", ""]
        # What the clips show, checked by eye on sampled frames (there are no labels for these clips).
        by_eye = {
            "Example of Hi-Definition Video Surveillance of a Factory Floor - by CCTVDOC.COM.mp4":
                "workers in orange hi-vis vests and no helmets, 5 to 7 people around a table. The flags fit (no helmet); the one COMPLIANT is probably a false compliance "
                "(no helmet is visible on anyone in the sampled frames); the many UNVERIFIABLE are small or overlapping people. Over capacity (more than 2) is correct.",
            "_ Hikvision ViewStar 8 Megapixel warehouse pallet company camera.mp4":
                "two or three workers in caps and dark shirts, no helmets or vests. The flags fit; nothing was called compliant.",
            "vtest.avi": "pedestrians on a campus path, nobody wearing a helmet or vest. Every flag is true; most people are small and were left UNVERIFIABLE. Over capacity (more than 2) is correct.",
            "PPE-test.mp4": "two workers: one with a white helmet and a hi-vis vest, one with a yellow helmet and no vest. Exactly right: one COMPLIANT, one flagged.",
        }
        md += ["### What the rules raised on these clips, against what the clips show (by eye; there are no labels)", ""]
        for c in real["clips"]:
            occ = c["head_count"]["decisions"]
            pd = c["ppe_decisions"] or {}
            ppe_text = ", ".join(f"{pd[k]} {label}" for k, label in (("COMPLIANT", "compliant"), ("POTENTIAL_VIOLATION", "flagged"), ("UNVERIFIABLE", "could not verify")) if pd.get(k)) or "nothing"
            md.append(f"- **{c['clip']}**: helmet and vest {ppe_text}; head count {len(occ)} decision(s)"
                      + (" (" + "; ".join(f"{d['status']} {d['outcome']} at {d['at_s']} s" for d in occ[:6]) + ")" if occ else "")
                      + (f". By eye: {by_eye[c['clip']]}" if c["clip"] in by_eye else "."))
        md.append("")

    md += ["## 4. The human review loop (§14.F)", "",
           "Not measured on a reviewed set of clips: it needs people to confirm or dismiss every flag of a recorded run. The Evaluation screen shows the organisation's own figures as reviews "
           "happen (flags judged, the share people agreed with, the reasons given, and how many could-not-verify decisions were later found real), from the same database function as the "
           "Reports page.", "",
           "## 5. What is not measured, and why", "",
           "- **Own footage (§14.A as planned).** No segments of workers recorded on site with known equipment. Section 1 uses still labelled images with camera jitter instead; it cannot show "
           "the effect of people walking, turning or being hidden.",
           "- **Staged falls (§14.C).** No recorded falls, so man-down recall is not stated. Scripted falls and normal real footage only show the logic and the absence of false alarms over a few minutes.",
           "- **Human-judged precision (§14.F).** Needs a reviewed run; the screen will show it as reviews come in.",
           "- **Identity on (§14.E second target).** The identity layer is not part of this product, so only the identity-off speed is reported.", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
